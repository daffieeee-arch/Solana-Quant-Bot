"""lab/core/src/tau/table.rs from backtest/tau_empirical.json: the empirical tolerance quantiles of backtest.replay.Tau
as f64 bit constants, so lab/core needs no JSON parser (M1 C2, research/m1-c2-positionsim-spec-2026-10-19.md D5).

  python core/tools/tau_table.py > core/src/tau/table.rs      (run from lab/; backtest/tests/test_tau_table.py pins it)
"""

import hashlib
import json
import os
import struct

LAB = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
JSON = os.path.join(LAB, "backtest", "tau_empirical.json")
SIDES = ("buy", "sell")


def _bits(x):
    return struct.unpack("<Q", struct.pack("<d", float(x)))[0]


def _venue(name, t, buckets):
    rows = []
    for side in SIDES:
        cells = []
        for b in range(buckets):
            qs = t.get(f"{side}:{b}") or []
            cells.append("&[" + ", ".join(f"f64::from_bits(0x{_bits(x):016x})" for x in qs) + "]")
        rows.append("    [\n" + "".join(f"        {c},\n" for c in cells) + "    ],\n")
    return f"pub const {name}: [[&[f64]; {buckets}]; 2] = [\n" + "".join(rows) + "];\n"


def generate():
    with open(JSON, "rb") as f:
        raw = f.read()
    t = json.loads(raw)
    edges = t["size_buckets_lamports"]
    assert all(type(e) is int for e in edges) and edges == sorted(edges)
    buckets = len(edges) + 1  # replay._bucket: 0 .. len(edges)
    return ("//! Generated by lab/core/tools/tau_table.py from backtest/tau_empirical.json: do not edit.\n"
            "//! [side: buy, sell][size bucket] -> the quantiles (`quantiles_step` apart), as f64 bits; an empty list is a\n"
            "//! bucket the JSON has no quantiles for (Tau.tol gives None).\n\n"
            f"pub const SHA256: &str = \"{hashlib.sha256(raw).hexdigest()}\";\n"
            f"pub const SIZE_BUCKETS: [i128; {len(edges)}] = [{', '.join(f'{e:_}' for e in edges)}];\n"
            + _venue("CURVE", t["table"], buckets) + _venue("POOL", t["pool_table"], buckets))


if __name__ == "__main__":
    print(generate(), end="")
