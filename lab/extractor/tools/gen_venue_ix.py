"""Write lab/extractor/src/venue_ix.rs from the pinned IDLs (idl/pump.json, idl/pump_amm.json, idl/venues/*.json; see
idl/venues/SOURCES.md): per instruction the program label, the Anchor discriminator, the name and the position of its
pool account (the first account named in POOL_ACCOUNTS; nested account groups flattened in IDL order). Standard
library only; the IDLs are data. The Rust test venue_ix_matches_the_pinned_idls checks the output against the files.

  python3 -I lab/extractor/tools/gen_venue_ix.py        (from the repo root)
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXTRACTOR = os.path.dirname(HERE)
# (label as in PROGRAM_LABELS, IDL file relative to lab/extractor/idl)
IDLS = [
    ("pump", "pump.json"),
    ("pump_amm", "pump_amm.json"),
    ("raydium_cpmm", "venues/raydium_cpmm.json"),
    ("raydium_clmm", "venues/raydium_clmm.json"),
    ("raydium_launchlab", "venues/raydium_launchlab.json"),
    ("meteora_dlmm", "venues/meteora_dlmm.json"),
    ("meteora_damm_v1", "venues/meteora_damm_v1.json"),
    ("meteora_damm_v2", "venues/meteora_damm_v2.json"),
    ("meteora_dbc", "venues/meteora_dbc.json"),
    ("orca_whirlpool", "venues/orca_whirlpool.json"),
]
POOL_ACCOUNTS = ("pool_state", "lb_pair", "whirlpool", "whirlpool_one", "pool", "bonding_curve", "virtual_pool", "amm")


def account_names(accounts):
    out = []
    for a in accounts:
        if "accounts" in a:
            out += account_names(a["accounts"])
        else:
            out.append(a["name"])
    return out


def entries():
    """[(label, discriminator bytes, name, pool position or None)] in IDL order per program."""
    out = []
    for label, rel in IDLS:
        with open(os.path.join(EXTRACTOR, "idl", rel)) as f:
            idl = json.load(f)
        for ix in idl["instructions"]:
            disc = ix["discriminator"]
            if len(disc) != 8:
                raise SystemExit(f"{label} {ix['name']}: discriminator is not 8 bytes")
            names = account_names(ix.get("accounts", []))
            pool = next((i for i, n in enumerate(names) if n in POOL_ACCOUNTS), None)
            if pool is not None and pool > 255:
                raise SystemExit(f"{label} {ix['name']}: pool account at {pool}")
            out.append((label, disc, ix["name"], pool))
    return out


def render(rows):
    lines = [
        "// Generated by lab/extractor/tools/gen_venue_ix.py from the pinned IDLs (idl/venues/SOURCES.md): do not edit.",
        "// The test venue_ix_matches_the_pinned_idls checks it against the files.",
        "",
        "/// The venue census's Anchor instructions: (program label as in PROGRAM_LABELS, discriminator, instruction name,",
        "/// position of the pool account in the instruction's accounts).",
        f"pub const VENUE_IXS: [(&str, [u8; 8], &str, Option<u8>); {len(rows)}] = [",
    ]
    for label, disc, name, pool in rows:
        d = ", ".join(str(b) for b in disc)
        p = "None" if pool is None else f"Some({pool})"
        lines.append(f'    ("{label}", [{d}], "{name}", {p}),')
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    rows = entries()
    path = os.path.join(EXTRACTOR, "src", "venue_ix.rs")
    with open(path, "w") as f:
        f.write(render(rows))
    print(f"{path}: {len(rows)} instructions")


if __name__ == "__main__":
    sys.exit(main())
